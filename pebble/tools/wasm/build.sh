#!/bin/sh
# Compile the SRP crypto WASM module and regenerate the embedded base64 TS file.
# Requires: Homebrew LLVM (wasm32 target) + lld (wasm-ld).
set -eu
DIR=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
LLVM=/opt/homebrew/opt/llvm/bin
export PATH="/opt/homebrew/bin:$PATH"

"$LLVM/clang" --target=wasm32 -nostdlib \
  -Wl,--no-entry -Wl,--export-dynamic -Wl,--allow-undefined \
  -Wl,-z,stack-size=65536 -O3 \
  -o "$DIR/srpcrypto.wasm" "$DIR/srpcrypto.c"

B64=$(base64 < "$DIR/srpcrypto.wasm" | tr -d '\n')
OUT="$DIR/../../src-ts/pkjs/wasm-crypto-bytes.ts"
{
  echo "// AUTO-GENERATED by tools/wasm/build.sh — do not edit by hand."
  echo "// Base64 of tools/wasm/srpcrypto.wasm (SHA-256/PBKDF2/2048-bit Montgomery modexp)."
  echo "export const WASM_CRYPTO_B64 ="
  echo "  \"$B64\";"
} > "$OUT"
echo "wrote $OUT ($(printf %s "$B64" | wc -c | tr -d ' ') b64 chars)"
